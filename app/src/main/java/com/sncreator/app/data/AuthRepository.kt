package com.sncreator.app.data

import android.app.Activity
import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.FirebaseApp
import com.google.firebase.FirebaseNetworkException
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import com.sncreator.app.BuildConfig
import com.sncreator.app.model.AppError
import com.sncreator.app.model.AuthenticatedUser
import kotlinx.coroutines.channels.awaitClose
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.tasks.await

sealed class AuthResult {
    data class Success(val user: AuthenticatedUser) : AuthResult()
    data class Failure(val error: AppError) : AuthResult()
}

interface AuthRepository {
    val authStateFlow: Flow<AuthenticatedUser?>
    fun getCurrentUser(): AuthenticatedUser?
    suspend fun signInWithGoogle(activityContext: Context): AuthResult
    suspend fun getValidIdToken(forceRefresh: Boolean = false): Result<String>
    suspend fun signOut()
}

class FirebaseGoogleAuthRepository(
    private val appContext: Context
) : AuthRepository {

    private fun isFirebaseConfigured(): Boolean {
        return runCatching {
            if (FirebaseApp.getApps(appContext).isNotEmpty()) {
                true
            } else {
                FirebaseApp.initializeApp(appContext) != null
            }
        }.getOrDefault(false)
    }

    private fun resolveWebClientId(): String {
        val fromBuildConfig = BuildConfig.FIREBASE_WEB_CLIENT_ID.trim()
        if (fromBuildConfig.isNotEmpty() && !fromBuildConfig.startsWith("YOUR_")) {
            return fromBuildConfig
        }
        // Fallback to default_web_client_id generated by google-services plugin when app/google-services.json is present
        val resId = appContext.resources.getIdentifier(
            "default_web_client_id",
            "string",
            appContext.packageName
        )
        return if (resId != 0) appContext.getString(resId).trim() else ""
    }

    private fun FirebaseUser.toDomainUser(): AuthenticatedUser {
        return AuthenticatedUser(
            uid = uid,
            displayName = displayName?.trim().orEmpty(),
            email = email,
            photoUrl = photoUrl?.toString()
        )
    }

    override val authStateFlow: Flow<AuthenticatedUser?> = callbackFlow {
        if (!isFirebaseConfigured()) {
            trySend(null)
            awaitClose { }
            return@callbackFlow
        }

        val firebaseAuth = FirebaseAuth.getInstance()
        val listener = FirebaseAuth.AuthStateListener { auth ->
            trySend(auth.currentUser?.toDomainUser())
        }
        firebaseAuth.addAuthStateListener(listener)

        awaitClose {
            firebaseAuth.removeAuthStateListener(listener)
        }
    }

    override fun getCurrentUser(): AuthenticatedUser? {
        if (!isFirebaseConfigured()) return null
        return runCatching {
            FirebaseAuth.getInstance().currentUser?.toDomainUser()
        }.getOrNull()
    }

    override suspend fun signInWithGoogle(activityContext: Context): AuthResult {
        if (!isFirebaseConfigured()) {
            return AuthResult.Failure(
                AppError.AuthMisconfigured(
                    "Firebase is not configured in this build yet. Add your app/google-services.json (package com.sncreator.app + SHA-1 fingerprint) as documented in README.md and rebuild."
                )
            )
        }

        val webClientId = resolveWebClientId()
        if (webClientId.isEmpty()) {
            return AuthResult.Failure(
                AppError.AuthMisconfigured(
                    "Google Web Client ID is missing. Enable Google Sign-In in Firebase Authentication and ensure app/google-services.json or FIREBASE_WEB_CLIENT_ID is configured."
                )
            )
        }

        if (activityContext !is Activity) {
            return AuthResult.Failure(
                AppError.Unknown("Google Sign-In requires an active screen context. Please tap Retry.")
            )
        }

        return try {
            val credentialManager = CredentialManager.create(activityContext)
            val googleIdOption = GetGoogleIdOption.Builder()
                .setFilterByAuthorizedAccounts(false)
                .setServerClientId(webClientId)
                .setAutoSelectEnabled(false)
                .build()

            val request = GetCredentialRequest.Builder()
                .addCredentialOption(googleIdOption)
                .build()

            val credentialResponse = credentialManager.getCredential(
                context = activityContext,
                request = request
            )

            val credential = credentialResponse.credential
            if (
                credential is CustomCredential &&
                credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
            ) {
                val googleIdTokenCredential = GoogleIdTokenCredential.createFrom(credential.data)
                val firebaseCredential =
                    GoogleAuthProvider.getCredential(googleIdTokenCredential.idToken, null)
                val authResult =
                    FirebaseAuth.getInstance().signInWithCredential(firebaseCredential).await()
                val user = authResult.user?.toDomainUser()
                if (user != null) {
                    AuthResult.Success(user)
                } else {
                    AuthResult.Failure(AppError.Unknown("Google authentication succeeded, but no user profile was returned."))
                }
            } else {
                AuthResult.Failure(AppError.Unknown("Unsupported credential type returned by Google Sign-In."))
            }
        } catch (_: GetCredentialCancellationException) {
            AuthResult.Failure(AppError.AuthCancelled)
        } catch (_: NoCredentialException) {
            AuthResult.Failure(
                AppError.AuthMisconfigured(
                    "No Google account is signed in on this device, or SHA-1 / OAuth client setup in Firebase does not match this debug APK. Check Google account settings or Firebase SHA-1 setup."
                )
            )
        } catch (_: FirebaseNetworkException) {
            AuthResult.Failure(AppError.Offline)
        } catch (e: Exception) {
            val msg = e.localizedMessage.orEmpty()
            if (msg.contains("network", ignoreCase = true)) {
                AuthResult.Failure(AppError.Offline)
            } else {
                AuthResult.Failure(
                    AppError.Unknown("Google sign-in failed: ${msg.ifBlank { "Please verify network and Firebase SHA-1 configuration." }}")
                )
            }
        }
    }

    override suspend fun getValidIdToken(forceRefresh: Boolean): Result<String> {
        if (!isFirebaseConfigured()) {
            return Result.failure(IllegalStateException("Firebase is not configured."))
        }
        val currentUser = FirebaseAuth.getInstance().currentUser
            ?: return Result.failure(IllegalStateException("Not signed in."))

        return runCatching {
            val tokenResult = currentUser.getIdToken(forceRefresh).await()
            val token = tokenResult.token
            if (token.isNullOrBlank()) {
                throw IllegalStateException("Received empty Firebase authentication token.")
            }
            token
        }
    }

    override suspend fun signOut() {
        runCatching {
            if (isFirebaseConfigured()) {
                FirebaseAuth.getInstance().signOut()
            }
        }
        runCatching {
            CredentialManager.create(appContext).clearCredentialState(ClearCredentialStateRequest())
        }
    }
}
